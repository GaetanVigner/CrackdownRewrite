#!/usr/bin/env python3
"""Progress of the native renderer work, as a chart for the README.

Writes docs/progress/history.json and docs/progress/progress.svg from:
- the git history: for each day with commits on the current branch (first parent, last commit of the day), how many
  of the title's D3D runtime entry points (docs/progress/d3d_entry_points.txt) the port hooks: every draw, state flush,
  resolve and command buffer replay the native renderer takes over goes through one of them;
- docs/progress/measurements.json, appended by hand after each capture comparison: the share of GPU draws whose state
  the HLE draw records reproduce exactly, render passes covered, and the roadmap.

Usage: python tools/progress.py [--worktree]   (--worktree adds today's uncommitted sources as the last point)
Standard library only.
"""
import argparse
import json
import re
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'docs' / 'progress'
HOOK = re.compile(r'(?:CRACKDOWN_BIND(?:_REPLACEMENT)?\(|REX_HOOK(?:_RAW)?\(sub_)(826[A-C][0-9A-F]{4})\b')


def git(*args):
    return subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, encoding='utf-8',
                          errors='replace').stdout


def entry_points():
    lines = (OUT / 'd3d_entry_points.txt').read_text(encoding='utf-8').splitlines()
    return {line.strip().upper() for line in lines if line.strip() and not line.startswith('#')}


def hooked(commit, api):
    # git grep on a commit prints "<commit>:<path>:<line>"; on the work tree just "<path>:<line>".
    args = ['grep', '-h', '-E', r'(CRACKDOWN_BIND|REX_HOOK)']
    if commit:
        args.append(commit)
    text = git(*args, '--', 'src')
    return sorted(api & {m.group(1).upper() for m in HOOK.finditer(text)})


def days():
    out = {}
    for line in git('log', '--first-parent', '--date=short', '--format=%ad %H').splitlines():
        day, commit = line.split()
        out.setdefault(day, commit)  # newest first: the first commit seen is the day's last
    return sorted(out.items())


def svg(history, measurements, api_total):
    width, left, right = 960, 70, 30
    plot_w = width - left - right
    panel_h, gap, top = 210, 70, 70
    roadmap_h = 120
    height = top + 2 * panel_h + gap + 50 + roadmap_h
    all_days = sorted({d for d, _ in history} | {c['date'] for c in measurements['captures']})
    first, last = date.fromisoformat(all_days[0]), date.fromisoformat(all_days[-1])
    span = max(1, (last - first).days)

    def x(day):
        return left + plot_w * (date.fromisoformat(day) - first).days / span

    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
           'font-family="Segoe UI, Helvetica, Arial, sans-serif" font-size="12">',
           '<style>.t{fill:#8b949e}.h{fill:#8b949e;font-size:15px;font-weight:600}.g{stroke:#8b949e;stroke-opacity:.25}'
           '.a{fill:none;stroke:#40a6f2;stroke-width:2.5}.d{fill:none;stroke:#8b949e;stroke-width:1.5;'
           'stroke-dasharray:6 4}.m{fill:none;stroke:#26a269;stroke-width:2.5}</style>',
           f'<text class="h" x="{left}" y="28">Crackdown native renderer: progress</text>',
           f'<text class="t" x="{left}" y="48">Generated by tools/progress.py on {date.today().isoformat()}</text>']

    def panel(y0, title, maximum, unit, series, declared=None):
        out.append(f'<text class="h" x="{left}" y="{y0 - 12}">{title}</text>')
        for i in range(5):
            v = maximum * i / 4
            y = y0 + panel_h - panel_h * i / 4
            out.append(f'<line class="g" x1="{left}" x2="{left + plot_w}" y1="{y:.1f}" y2="{y:.1f}"/>')
            out.append(f'<text class="t" x="{left - 8}" y="{y + 4:.1f}" text-anchor="end">{v:.0f}{unit}</text>')
        if declared is not None:
            yd = y0 + panel_h - panel_h * declared / maximum
            out.append(f'<line class="d" x1="{left}" x2="{left + plot_w}" y1="{yd:.1f}" y2="{yd:.1f}"/>')
        for cls, points in series:
            pts = ' '.join(f'{x(d):.1f},{y0 + panel_h - panel_h * v / maximum:.1f}' for d, v in points)
            out.append(f'<polyline class="{cls}" points="{pts}"/>')
            for d, v in points:
                px, py = x(d), y0 + panel_h - panel_h * v / maximum
                out.append(f'<circle cx="{px:.1f}" cy="{py:.1f}" r="3.5" fill="{"#40a6f2" if cls == "a" else "#26a269"}">'
                           f'<title>{d}: {v:g}{unit}</title></circle>')
        for d in all_days[::max(1, len(all_days) // 8)] + [all_days[-1]]:
            out.append(f'<text class="t" x="{x(d):.1f}" y="{y0 + panel_h + 18}" text-anchor="middle">{d[5:]}</text>')

    hooks = [(d, len(h['hooked'])) for d, h in history]
    panel(top + 20, f'D3D runtime entry points hooked by the port: {hooks[-1][1]} of {api_total} (dashed)',
          api_total * 1.1, '', [('a', hooks)], declared=api_total)
    caps = {}
    for c in measurements['captures']:
        caps[c['date']] = c['draws_exact_percent']  # the day's last measurement
    last_cap = measurements['captures'][-1]
    title = f'GPU draws whose state the HLE draw records reproduce exactly: {last_cap["draws_exact_percent"]:g}%'
    if 'passes_exact' in last_cap:
        title += (f'  |  render passes exact: {last_cap["passes_exact"]} of {measurements["passes_total"]}, '
                  f'native: {last_cap["passes_native"]}')
    panel(top + panel_h + gap + 20, title, 100, '%', [('m', sorted(caps.items()))])

    y = top + 2 * panel_h + gap + 75
    out.append(f'<text class="h" x="{left}" y="{y}">Roadmap (HLE_RENDERER_PLAN.md)</text>')
    colors = {'done': '#26a269', 'in progress': '#40a6f2', 'next': '#e5a50a', 'planned': '#8b949e'}
    steps = measurements['roadmap']
    w = plot_w / len(steps)
    for i, step in enumerate(steps):
        bx = left + i * w
        color = colors.get(step['status'], '#8b949e')
        fill_opacity = '1' if step['status'] != 'planned' else '.35'
        out.append(f'<rect x="{bx + 2:.1f}" y="{y + 14}" width="{w - 4:.1f}" height="30" rx="5" fill="{color}" '
                   f'fill-opacity="{fill_opacity}"><title>{step["id"]}: {step["name"]} ({step["status"]})</title></rect>')
        out.append(f'<text x="{bx + w / 2:.1f}" y="{y + 34}" text-anchor="middle" fill="#ffffff" font-weight="600">'
                   f'{step["id"]}</text>')
        out.append(f'<text class="t" x="{bx + w / 2:.1f}" y="{y + 60}" text-anchor="middle" font-size="10.5">'
                   f'{step["name"]}</text>')
    legend_y = y + 84
    for i, (status, color) in enumerate(colors.items()):
        lx = left + i * 130
        out.append(f'<rect x="{lx}" y="{legend_y}" width="12" height="12" rx="2" fill="{color}"/>')
        out.append(f'<text class="t" x="{lx + 18}" y="{legend_y + 10}">{status}</text>')
    out.append('</svg>')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--worktree', action='store_true', help="add the uncommitted sources as today's point")
    args = parser.parse_args()
    api = entry_points()
    history = [(day, {'commit': commit[:9], 'hooked': hooked(commit, api)}) for day, commit in days()]
    if args.worktree:
        today = date.today().isoformat()
        history = [h for h in history if h[0] != today] + [(today, {'commit': 'worktree', 'hooked': hooked(None, api)})]
    measurements = json.loads((OUT / 'measurements.json').read_text(encoding='utf-8'))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'history.json').write_text(json.dumps({
        'd3d_entry_points': len(api),
        'days': [{'date': d, 'commit': h['commit'], 'hooked': len(h['hooked']), 'functions': h['hooked']}
                 for d, h in history],
        'captures': measurements['captures'],
    }, indent=2) + '\n', encoding='utf-8')
    (OUT / 'progress.svg').write_text(svg(history, measurements, len(api)), encoding='utf-8')
    print(f'{len(history)} days, {len(history[-1][1]["hooked"])} of {len(api)} D3D entry points hooked; '
          f'wrote {OUT / "history.json"} and {OUT / "progress.svg"}')
    # The progress map (treemaps and tables of what is native).
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import progress_map
    progress_map.main()


if __name__ == '__main__':
    main()
